# -*- coding: utf-8 -*-
"""A 股交易日历（轻量版）

只解决一个判断：**今天是不是交易日**。
周末由 weekday 直接排除；落在周一~周五的法定休市日按交易所公告硬编码。

数据来源：上海证券交易所《关于上海证券交易所 2026 年部分节假日休市安排的通知》
          （上证公告〔2025〕45 号，2025-12-22），沪深北三所同步。
          调休上班的周六/周日（如 2026-02-14、2026-10-10）交易所明确「为周末休市」，
          不参与交易，故无需单列。

维护：每年 12 月交易所发布次年安排后，补一组 CLOSED 条目即可。
      表外年份自动回退为「仅排除周末 + 标注待确认」，不会误报为交易日。
"""
from __future__ import annotations

import datetime as dt

# 落在工作日（周一~周五）的法定休市日 → 节日名
CLOSED_WEEKDAY = {
    # 元旦：1/1(四)~1/3(六)，1/5(一) 开市
    "2026-01-01": "元旦", "2026-01-02": "元旦",
    # 春节：2/15(日)~2/23(一)，2/24(二) 开市
    "2026-02-16": "春节", "2026-02-17": "春节", "2026-02-18": "春节",
    "2026-02-19": "春节", "2026-02-20": "春节", "2026-02-23": "春节",
    # 清明：4/4(六)~4/6(一)，4/7(二) 开市
    "2026-04-06": "清明",
    # 劳动节：5/1(五)~5/5(二)，5/6(三) 开市
    "2026-05-01": "劳动节", "2026-05-04": "劳动节", "2026-05-05": "劳动节",
    # 端午：6/19(五)~6/21(日)，6/22(一) 开市
    "2026-06-19": "端午",
    # 中秋：9/25(五)~9/27(日)，9/28(一) 开市
    "2026-09-25": "中秋",
    # 国庆：10/1(四)~10/7(三)，10/8(四) 开市
    "2026-10-01": "国庆", "2026-10-02": "国庆", "2026-10-05": "国庆",
    "2026-10-06": "国庆", "2026-10-07": "国庆",
}

# 已确认覆盖的年份（表外年份的判断需谨慎，只能靠周末排除）
COVERED_YEARS = {2026}


def closed_reason(d: dt.date) -> str | None:
    """休市原因；交易日返回 None。"""
    if d.weekday() >= 5:
        return "周末"
    return CLOSED_WEEKDAY.get(d.isoformat())


def is_trading_day(d: dt.date) -> bool:
    return closed_reason(d) is None


def covered(d: dt.date) -> bool:
    """该日期的年份是否有官方日历覆盖"""
    return d.year in COVERED_YEARS or d.weekday() >= 5


def describe(d: dt.date) -> str:
    """给人看的一句话：今天是交易日 / 因什么休市"""
    r = closed_reason(d)
    if r:
        return f"{d.isoformat()} 休市（{r}）"
    if covered(d):
        return f"{d.isoformat()} 交易日"
    return f"{d.isoformat()} 按工作日推定为交易日（{d.year} 年休市表未收录，待确认）"
